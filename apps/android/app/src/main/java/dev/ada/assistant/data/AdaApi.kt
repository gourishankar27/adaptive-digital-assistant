class HttpAdaApi(callTimeoutMillis: Long = 65_000) : AdaApi {
    // No automatic retry of an ambiguous POST and no credential-bearing redirects.
    private val client = OkHttpClient.Builder()
        .connectTimeout(10, TimeUnit.SECONDS).readTimeout(60, TimeUnit.SECONDS)
        .callTimeout(callTimeoutMillis, TimeUnit.MILLISECONDS).followRedirects(false).followSslRedirects(false)
        .retryOnConnectionFailure(false).build()

    private fun oneShotJsonBody(body: String): RequestBody {
        val buffered = body.toRequestBody("application/json; charset=utf-8".toMediaType())
        return object : RequestBody() {
            override fun contentType() = buffered.contentType()
            override fun contentLength() = buffered.contentLength()
            // OkHttp can follow 503 Retry-After: 0 even when connection retries are disabled.
            // Each explicit API invocation creates a fresh body; the client cannot replay it itself.
            override fun isOneShot() = true
            override fun writeTo(sink: BufferedSink) = buffered.writeTo(sink)
        }
    }

    private suspend inline fun <reified T> call(
        connection: ConnectionCredential, path: String, body: String? = null,
        query: Map<String, String?> = emptyMap(),
    ): ApiResult<T> = withContext(Dispatchers.IO) {
        val url = connection.server.newBuilder().addPathSegments("v1/$path")
        query.forEach { (key, value) -> if (value != null) url.addQueryParameter(key, value) }
        val builder = Request.Builder().url(url.build()).header("Authorization", "Bearer ${connection.token}")
            .header("Accept", "application/json")
        if (body != null) builder.post(oneShotJsonBody(body))
        try {
            client.newCall(builder.build()).execute().use { response ->
                if (!response.isSuccessful) return@withContext sanitizedFailure(response)
                val json = response.body?.string() ?: return@withContext ApiResult.Failure(ApiFailure.IncompatibleContract)
                ApiResult.Success(adaJson.decodeFromString<T>(json))
            }
        } catch (_: InterruptedIOException) { ApiResult.Failure(ApiFailure.Timeout)
        } catch (_: IOException) { ApiResult.Failure(ApiFailure.Unreachable)
        } catch (_: SerializationException) { ApiResult.Failure(ApiFailure.IncompatibleContract)
        } catch (_: IllegalArgumentException) { ApiResult.Failure(ApiFailure.IncompatibleContract) }
    }
    private fun sanitizedFailure(response: Response): ApiResult.Failure {
        val reason = when (response.code) {
            401 -> ApiFailure.Unauthorized
            403 -> ApiFailure.Forbidden
            404 -> ApiFailure.NotFound
            409 -> ApiFailure.Conflict
            413 -> ApiFailure.TooLarge
            422 -> ApiFailure.Validation
            429, 503 -> ApiFailure.Busy(retryAfter(response.header("Retry-After")))
            502 -> ApiFailure.Provider
            else -> ApiFailure.Http(response.code)
        }
        // Only these fixed protocol codes can influence product wording. Validation input,
        // arbitrary detail and authentication error bodies are never retained or rendered.
        val code = if (response.code in setOf(409, 413, 422, 502)) try {
            val detail = (adaJson.parseToJsonElement(response.peekBody(1024).string()) as? JsonObject)?.get("detail") as? JsonPrimitive
            detail?.takeIf { it.isString }?.content?.takeIf { it in safeErrorCodes }
        } catch (_: Exception) { null } else null
        return ApiResult.Failure(reason, code)
    }
    private fun retryAfter(header: String?): Long? {
        if (header == null) return null
        header.toLongOrNull()?.let { return it.takeIf { seconds -> seconds >= 0 } }
        return try {
            val millis = ZonedDateTime.parse(header, DateTimeFormatter.RFC_1123_DATE_TIME).toInstant().toEpochMilli() - System.currentTimeMillis()
            if (millis <= 0) 0 else (millis + 999) / 1000
        } catch (_: Exception) { null }
    }
    private val safeErrorCodes = setOf(
        "idempotency_key_reused", "retry_history_changed", "request_in_progress", "conversation_busy",
        "request_conflict", "request_superseded", "unsupported_prompt_upgrade", "message_exceeds_context_budget",
        "provider_unavailable", "model_not_found", "provider_timeout", "invalid_response", "interrupted",
    )
    private fun page(limit: Int, offset: Int) = mapOf("limit" to limit.toString(), "offset" to offset.toString())
    override suspend fun me(connection: ConnectionCredential) = call<MeDto>(connection, "me")
    override suspend fun capabilities(connection: ConnectionCredential) = call<CapabilitiesDto>(connection, "capabilities")
    override suspend fun personalities(connection: ConnectionCredential, limit: Int, offset: Int) = call<List<PersonalityDto>>(connection, "personalities", query = page(limit, offset))
    override suspend fun conversations(connection: ConnectionCredential, limit: Int, offset: Int) = call<List<ConversationDto>>(connection, "conversations", query = page(limit, offset))
    override suspend fun conversation(connection: ConnectionCredential, id: UUID) = call<ConversationDto>(connection, "conversations/$id")
    override suspend fun events(connection: ConnectionCredential, id: UUID, limit: Int, offset: Int) = call<List<EventDto>>(connection, "conversations/$id/events", query = page(limit, offset))
    override suspend fun request(connection: ConnectionCredential, id: UUID) = call<RequestDto>(connection, "requests/$id")
    override suspend fun trace(connection: ConnectionCredential, id: UUID) = call<TraceDto>(connection, "requests/$id/retrieval")
    override suspend fun scopes(connection: ConnectionCredential, limit: Int, offset: Int) = call<List<ScopeDto>>(connection, "scopes", query = page(limit, offset))
    override suspend fun scope(connection: ConnectionCredential, id: UUID) = call<ScopeDto>(connection, "scopes/$id")
    override suspend fun source(connection: ConnectionCredential, id: UUID) = call<SourceVersionDto>(connection, "source-versions/$id")
    override suspend fun sources(connection: ConnectionCredential, scope: UUID, limit: Int, offset: Int) = call<List<SourceVersionDto>>(connection, "scopes/$scope/source-versions", query = page(limit, offset))
    override suspend fun claim(connection: ConnectionCredential, id: UUID) = call<ClaimDto>(connection, "claims/$id")
    override suspend fun claims(connection: ConnectionCredential, scope: UUID, limit: Int, offset: Int, history: Boolean, asOf: String?) = call<List<ClaimDto>>(connection, "scopes/$scope/claims", query = page(limit, offset) + mapOf("history" to history.toString(), "as_of" to asOf))
    override suspend fun createPersonality(connection: ConnectionCredential, body: PersonalityInputDto) = call<PersonalityDto>(connection, "personalities", adaJson.encodeToString(body))
    override suspend fun createConversation(connection: ConnectionCredential, body: ConversationInputDto) = call<ConversationDto>(connection, "conversations", adaJson.encodeToString(body))
    override suspend fun upgradePrompt(connection: ConnectionCredential, id: UUID) = call<PromptUpgradeDto>(connection, "conversations/$id/prompt-upgrade", "{}")
    override suspend fun send(connection: ConnectionCredential, conversation: UUID, body: ChatInputDto) = call<RequestDto>(connection, "conversations/$conversation/messages", adaJson.encodeToString(body))
    override suspend fun createScope(connection: ConnectionCredential, body: ScopeInputDto) = call<ScopeDto>(connection, "scopes", adaJson.encodeToString(body))
    override suspend fun createNote(connection: ConnectionCredential, scope: UUID, body: NoteInputDto) = call<SourceVersionDto>(connection, "scopes/$scope/notes", adaJson.encodeToString(body))
    override suspend fun createClaim(connection: ConnectionCredential, scope: UUID, body: ClaimInputDto) = call<ClaimDto>(connection, "scopes/$scope/claims", adaJson.encodeToString(body))
    override suspend fun supersede(connection: ConnectionCredential, id: UUID, body: SupersedeInputDto) = call<ClaimDto>(connection, "claims/$id/supersede", adaJson.encodeToString(body))
    override suspend fun retrieve(connection: ConnectionCredential, scope: UUID, body: RetrieveInputDto) = call<RetrievalDto>(connection, "scopes/$scope/retrieve", adaJson.encodeToString(body))
}

