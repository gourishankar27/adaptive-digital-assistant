// Deliberately not a data class: autogenerated toString/copy must not expose credentials.
class ConnectionCredential private constructor(val server: HttpUrl, internal val token: String) {
    companion object {
        val debugHttpHosts = setOf("10.0.2.2", "127.0.0.1", "localhost")
        fun parse(server: String, token: String, allowDebugHttp: Boolean): ConnectionCredential? {
            val url = server.trim().toHttpUrlOrNull() ?: return null
            if (url.username.isNotEmpty() || url.password.isNotEmpty() || url.query != null ||
                url.fragment != null || url.encodedPath != "/") return null
            if (url.scheme != "https" && !(allowDebugHttp && url.host in debugHttpHosts)) return null
            if (token.isBlank() || token.length > 200 || token.any { it.code !in 33..126 }) return null
            return ConnectionCredential(url, token)
        }
    }
}

sealed interface ApiResult<out T> {
    data class Success<T>(val value: T) : ApiResult<T>
    data class Failure(val reason: ApiFailure, val code: String? = null) : ApiResult<Nothing>
}
sealed interface ApiFailure {
    data object Unauthorized : ApiFailure
    data object Forbidden : ApiFailure
    data object NotFound : ApiFailure
    data object Conflict : ApiFailure
    data object TooLarge : ApiFailure
    data object Validation : ApiFailure
    data class Busy(val retryAfterSeconds: Long?) : ApiFailure
    data object Provider : ApiFailure
    data object Timeout : ApiFailure
    data object Unreachable : ApiFailure
    data object IncompatibleContract : ApiFailure
    data class Http(val status: Int) : ApiFailure
}

